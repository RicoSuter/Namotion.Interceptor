namespace HomeBlaze.Components;

/// <summary>Where a <see cref="TabLayout"/> shows its tab bar.</summary>
public enum TabPosition
{
    /// <summary>Above the content, with the tabs next to each other.</summary>
    Top,

    /// <summary>At the left of the content, with the tabs below each other.</summary>
    Left,

    /// <summary>At the right of the content, with the tabs below each other.</summary>
    Right,

    /// <summary>Below the content, with the tabs next to each other.</summary>
    Bottom
}
